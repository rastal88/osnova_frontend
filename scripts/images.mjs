// Image optimisation: for every file in src/assets/images/source writes resized AVIF,
// WebP and a JPEG/PNG fallback to src/assets/images/generated, plus index.ts that
// exports an ImageSource per image for the <Image> component:
//
//   import { hero } from '../assets/images/generated';
//   <Image image={hero} alt="..." sizes="100vw" priority />
//
// Run after adding or changing a source image: npm run images
// Uses sharp (dev dependency only, nothing of it reaches the bundle).

import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, join, parse } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'src/assets/images/source');
const outDir = join(root, 'src/assets/images/generated');

const WIDTHS = [640, 1280, 1920];
const INPUT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.svg']);
const QUALITY = { avif: 50, webp: 75, jpeg: 78 };

const camelCase = (name) =>
  name.replace(/[-_\s]+(.)/g, (_, char) => char.toUpperCase()).replace(/^\d/, '_$&');

async function optimise(file) {
  const { name, ext } = parse(file);
  const path = join(sourceDir, file);
  const meta = await sharp(path).metadata();
  const isSvg = ext.toLowerCase() === '.svg';
  const widths = WIDTHS.filter((width) => isSvg || width < meta.width);
  if (!isSvg && !widths.includes(meta.width) && widths.length < WIDTHS.length) {
    widths.push(meta.width);
  }
  // PNG only when transparency is really used (rendered SVGs always have an alpha channel)
  const { isOpaque } = await sharp(path).stats();
  const fallback = isOpaque ? 'jpeg' : 'png';
  const height = (width) => Math.round((meta.height * width) / meta.width);

  const variants = [];
  for (const width of widths) {
    // Vector sources are rendered at the target size instead of being upscaled
    const input = isSvg ? sharp(path, { density: (72 * width) / meta.width }) : sharp(path);
    const resized = input.resize({ width });
    for (const format of ['avif', 'webp', fallback]) {
      const fileName = `${name}-${width}.${format === 'jpeg' ? 'jpg' : format}`;
      const encoded =
        format === 'png'
          ? resized.clone().png({ compressionLevel: 9 })
          : resized.clone()[format]({ quality: QUALITY[format], mozjpeg: format === 'jpeg' });
      await encoded.toFile(join(outDir, fileName));
      variants.push({ width, format, fileName });
    }
  }
  return { name, id: camelCase(name), widths, fallback, width: widths.at(-1), height: height(widths.at(-1)), variants };
}

function renderIndex(images) {
  const lines = [
    '// Generated by `npm run images` from src/assets/images/source. Do not edit.',
    "import type { ImageSource } from '../../../components/Image/Image';",
    '',
  ];
  const exports = [];
  for (const image of images) {
    const vars = {};
    for (const { width, format, fileName } of image.variants) {
      const variable = `${image.id}${format[0].toUpperCase()}${format.slice(1)}${width}`;
      vars[`${format}-${width}`] = variable;
      lines.push(`import ${variable} from './${fileName}';`);
    }
    const srcSet = (format) =>
      image.widths.map((width) => `\${${vars[`${format}-${width}`]}} ${width}w`).join(', ');
    exports.push(
      `export const ${image.id}: ImageSource = {`,
      `  src: ${vars[`${image.fallback}-${image.width}`]},`,
      `  width: ${image.width},`,
      `  height: ${image.height},`,
      `  srcSet: \`${srcSet(image.fallback)}\`,`,
      `  avif: \`${srcSet('avif')}\`,`,
      `  webp: \`${srcSet('webp')}\`,`,
      '};',
      '',
    );
  }
  return [...lines, '', ...exports].join('\n');
}

const files = (await readdir(sourceDir)).filter((file) => INPUT.has(extname(file).toLowerCase())).sort();
await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const images = [];
for (const file of files) {
  images.push(await optimise(file));
  console.log(`images: ${file} → ${images.at(-1).variants.length} files`);
}
await writeFile(join(outDir, 'index.ts'), renderIndex(images));
console.log(`images: ${images.length} image(s) → src/assets/images/generated`);
