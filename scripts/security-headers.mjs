// Security headers of the site, written as an nginx snippet at build time (Dockerfile):
// the Content Security Policy depends on the analytics script (VITE_ANALYTICS_SCRIPT)
// and on CSP_EXTRA_ORIGINS, so it cannot be a fixed file.
//
// Usage: node scripts/security-headers.mjs > security-headers.conf
//
// Allowed besides the site itself: Cloudflare Turnstile (the captcha), the origin of
// the analytics script, the host of VITE_SENTRY_DSN (errors are sent there), and
// CSP_EXTRA_ORIGINS (space-separated, e.g. the collector of an analytics service that
// sends data to another host, like Google Analytics).

const TURNSTILE = 'https://challenges.cloudflare.com';

/** "https://cdn.example.com/script.js" -> "https://cdn.example.com"; "" or a path -> null. */
export function originOf(url) {
  try {
    const { origin } = new URL(url);
    return origin === 'null' ? null : origin;
  } catch {
    return null;
  }
}

/** The Content-Security-Policy value. */
export function contentSecurityPolicy({
  analyticsScript = '',
  sentryDsn = '',
  extraOrigins = '',
} = {}) {
  const extra = [originOf(analyticsScript), ...extraOrigins.split(/\s+/).map(originOf)].filter(
    Boolean,
  );
  const unique = (items) => [...new Set(items)].join(' ');
  const directives = {
    'default-src': "'self'",
    'script-src': unique(["'self'", TURNSTILE, ...extra]),
    // Ant Design writes its styles at run time
    'style-src': "'self' 'unsafe-inline'",
    'img-src': unique(["'self'", 'data:', 'blob:', ...extra]),
    'font-src': "'self' data:",
    'connect-src': unique(["'self'", originOf(sentryDsn), ...extra].filter(Boolean)),
    'frame-src': TURNSTILE,
    // Nobody shows the site in a frame (clickjacking)
    'frame-ancestors': "'none'",
    'form-action': "'self'",
    'base-uri': "'self'",
    'object-src': "'none'",
  };
  return Object.entries(directives)
    .map(([name, value]) => `${name} ${value}`)
    .join('; ');
}

/** The nginx snippet: `add_header` lines, included where the site's pages are served. */
export function securityHeaders(options = {}) {
  const headers = [
    ['Content-Security-Policy', contentSecurityPolicy(options)],
    // For browsers without frame-ancestors
    ['X-Frame-Options', 'DENY'],
    ['X-Content-Type-Options', 'nosniff'],
    ['Referrer-Policy', 'strict-origin-when-cross-origin'],
    ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), usb=()'],
    ['Cross-Origin-Opener-Policy', 'same-origin'],
  ];
  const lines = headers.map(([name, value]) => `add_header ${name} "${value}" always;`);
  // Only over HTTPS (the proxy in front says so); an empty value sends no header
  lines.push('add_header Strict-Transport-Security $hsts always;');
  return `# Generated by scripts/security-headers.mjs at build time\n${lines.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(
    securityHeaders({
      analyticsScript: process.env.VITE_ANALYTICS_SCRIPT ?? '',
      sentryDsn: process.env.VITE_SENTRY_DSN ?? '',
      extraOrigins: process.env.CSP_EXTRA_ORIGINS ?? '',
    }),
  );
}
